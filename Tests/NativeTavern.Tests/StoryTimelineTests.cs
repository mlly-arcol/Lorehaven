    [Theory]
    [InlineData(false, false)]
    [InlineData(false, true)]
    [InlineData(true, false)]
    [InlineData(true, true)]
    public async Task MessagesChangedDuringExtractionDoNotSaveStaleEventsOrAdvanceTheCursor(
        bool deleteSource, bool emptyResponse)
    {
        await using var fixture = await Fixture.CreateAsync();
        var session = await fixture.CreateSessionAsync();
        var firstId = await fixture.AddMessageAsync(session.Id, "OLD_EVENT");
        var nextId = await fixture.AddMessageAsync(session.Id, "NEXT_EVENT");
        fixture.Provider.Responses.Enqueue(emptyResponse
            ? """{"events":[]}"""
            : $$"""{"events":[{"messageId":{{firstId}},"title":"Stale event"}]}""");
        fixture.Provider.BeforeResponse = async () =>
        {
            if (deleteSource)
                await fixture.Messages.DeleteAsync(firstId);
            else
            {
                var message = (await fixture.Messages.GetBySessionAsync(session.Id)).First();
                message.Content = "EDITED_EVENT";
                await fixture.Messages.UpdateAsync(message);
            }
        };

        await Assert.ThrowsAsync<InvalidDataException>(() => fixture.Service.ExtractNewAsync(session.Id));

        Assert.Empty(await fixture.Service.GetEventsAsync(session.Id));
        Assert.Equal(deleteSource ? new[] { nextId } : new[] { firstId, nextId },
            (await fixture.Repository.GetNextSourceBatchAsync(session.Id, 16)).Select(x => x.Id));
        fixture.Provider.Responses.Enqueue(
            $$"""{"events":[{"messageId":{{nextId}},"title":"Current event"}]}""");
        var retry = await fixture.Service.ExtractNewAsync(session.Id);
        Assert.Equal(1, retry.AddedEvents);
        Assert.Equal(nextId, Assert.Single(await fixture.Service.GetEventsAsync(session.Id)).SourceMessageId);
        if (!deleteSource)
            Assert.Contains("EDITED_EVENT", fixture.Provider.Requests[1].Messages[1].Content);
        Assert.Empty(await fixture.Repository.GetNextSourceBatchAsync(session.Id, 16));
    }

