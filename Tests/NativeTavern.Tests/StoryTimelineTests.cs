    [Fact]
    public async Task InitializerMigratesExistingTimelineCursorAndUniqueIndex()
    {
        var root = Path.Combine(Path.GetTempPath(), "nt-timeline-migrate-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            var factory = new DatabaseConnectionFactory(Path.Combine(root, "data.db"));
            await using (var connection = factory.CreateConnection())
            {
                await connection.OpenAsync();
                await connection.ExecuteAsync(
                    "CREATE TABLE StoryTimelineScans(ChatSessionId INTEGER PRIMARY KEY,LastMessageId INTEGER NOT NULL DEFAULT 0);" +
                    "INSERT INTO StoryTimelineScans(ChatSessionId,LastMessageId) VALUES(42,7);" +
                    "CREATE TABLE StoryTimelineEvents(Id INTEGER PRIMARY KEY AUTOINCREMENT,ChatSessionId INTEGER NOT NULL," +
                    "SourceMessageId INTEGER NULL,Title TEXT NOT NULL,Detail TEXT NOT NULL DEFAULT ''," +
                    "IsAutoGenerated INTEGER NOT NULL DEFAULT 0,CreatedAt TEXT NOT NULL,UpdatedAt TEXT NOT NULL);" +
                    "CREATE UNIQUE INDEX UX_StoryTimelineEvents_AutoSource " +
                    "ON StoryTimelineEvents(ChatSessionId,SourceMessageId) " +
                    "WHERE IsAutoGenerated=1 AND SourceMessageId IS NOT NULL;");
            }

            await new DatabaseInitializer(factory, NullLogger<DatabaseInitializer>.Instance).InitializeAsync();

            await using var migrated = factory.CreateConnection();
            var columns = (await migrated.QueryAsync<string>(
                "SELECT name FROM pragma_table_info('StoryTimelineScans')")).ToArray();
            Assert.Contains("PartialMessageId", columns);
            Assert.Contains("PartialOffset", columns);
            Assert.Contains("PartialContentHash", columns);
            Assert.Equal(7, await migrated.ExecuteScalarAsync<long>(
                "SELECT LastMessageId FROM StoryTimelineScans WHERE ChatSessionId=42"));
            Assert.Contains("Title", await migrated.ExecuteScalarAsync<string>(
                "SELECT sql FROM sqlite_master WHERE name='UX_StoryTimelineEvents_AutoSource'"));
        }
        finally
        {
            SqliteConnection.ClearAllPools();
            Directory.Delete(root, true);
        }
    }

