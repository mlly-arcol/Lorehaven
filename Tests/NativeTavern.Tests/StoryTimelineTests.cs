    [Fact]
    public async Task ManualEventsCanBeEditedAndDeletedOnlyInTheirOwnSession()
    {
        await using var fixture = await Fixture.CreateAsync();
        var first = await fixture.CreateSessionAsync();
        var second = await fixture.CreateSessionAsync();
        var firstMessage = await fixture.AddMessageAsync(first.Id, "The gate opens.");
        var secondMessage = await fixture.AddMessageAsync(second.Id, "Another story.");

        var item = await fixture.Service.AddManualAsync(first.Id, firstMessage, "  Gate opens  ", "  A new path appears.  ");

        Assert.Equal("Gate opens", item.Title);
        Assert.Equal("A new path appears.", item.Detail);
        Assert.False(item.IsAutoGenerated);
        Assert.Equal(firstMessage, item.SourceMessageId);
        Assert.Equal(item.Id, Assert.Single(await fixture.Service.GetEventsAsync(first.Id)).Id);
        Assert.Empty(await fixture.Service.GetEventsAsync(second.Id));
        await Assert.ThrowsAsync<InvalidDataException>(() =>
            fixture.Service.AddManualAsync(first.Id, secondMessage, "Wrong session", ""));

        item.SourceMessageId = secondMessage;
        await Assert.ThrowsAsync<InvalidDataException>(() =>
            fixture.Service.UpdateAsync(item, "Wrong source", ""));
        item.SourceMessageId = firstMessage;
        var wrongSession = new StoryTimelineEvent
        {
            Id = item.Id, ChatSessionId = second.Id, SourceMessageId = secondMessage,
            CreatedAt = item.CreatedAt, UpdatedAt = item.UpdatedAt
        };
        Assert.False(await fixture.Service.UpdateAsync(wrongSession, "Wrong session", ""));

        Assert.True(await fixture.Service.UpdateAsync(item, "  Gate closes  ", "The way back is blocked."));
        Assert.False(await fixture.Service.DeleteAsync(second.Id, item.Id));
        Assert.Equal("Gate closes", Assert.Single(await fixture.Service.GetEventsAsync(first.Id)).Title);

        await fixture.Plugins.SetEnabledAsync("timeline.test", false);
        Assert.Empty(await fixture.Service.GetEventsAsync(first.Id));
        await fixture.Plugins.SetEnabledAsync("timeline.test", true);
        Assert.Equal(item.Id, Assert.Single(await fixture.Service.GetEventsAsync(first.Id)).Id);

        await fixture.Messages.DeleteAsync(firstMessage);
        var orphaned = Assert.Single(await fixture.Service.GetEventsAsync(first.Id));
        Assert.Null(orphaned.SourceMessageId); // The UI cannot jump to a deleted message.
        Assert.True(await fixture.Service.DeleteAsync(first.Id, item.Id));
        Assert.Empty(await fixture.Service.GetEventsAsync(first.Id));
    }

    [Fact]
    public async Task ExtractionScansOnlyNewMessagesAndRetainsRealSourceIds()
    {
        await using var fixture = await Fixture.CreateAsync();
        var session = await fixture.CreateSessionAsync();
        var other = await fixture.CreateSessionAsync();
        var ids = new List<long>();
        for (var index = 0; index < 16; index++)
            ids.Add(await fixture.AddMessageAsync(session.Id, $"turn-{index:D2}"));
        await fixture.AddMessageAsync(session.Id, "ignore-system", ChatRole.System);
        await fixture.AddMessageAsync(session.Id, "  ");
        var seventeenth = await fixture.AddMessageAsync(session.Id, "turn-16");
        var eighteenth = await fixture.AddMessageAsync(session.Id, "turn-17");
        var foreign = await fixture.AddMessageAsync(other.Id, "foreign story");

        fixture.Provider.Responses.Enqueue(
            $$"""{"events":[{"messageId":{{ids[0]}},"title":"Opening","detail":"The story begins."},{"messageId":{{ids[0]}},"title":"Opening"},{"messageId":{{foreign}},"title":"Foreign"},{"messageId":{{ids[15]}},"title":"Turning point"}]}""");
        var first = await fixture.Service.ExtractNewAsync(session.Id);

        Assert.Equal(16, first.ScannedMessages);
        Assert.Equal(2, first.AddedEvents);
        Assert.True(first.MayHaveMore);
        Assert.Equal(new long?[] { ids[0], ids[15] },
            (await fixture.Service.GetEventsAsync(session.Id)).Select(x => x.SourceMessageId));
        Assert.Equal(new[] { seventeenth, eighteenth },
            (await fixture.Repository.GetNextSourceBatchAsync(session.Id, 16)).Select(x => x.Id));
        var firstTranscript = fixture.Provider.Requests[0].Messages[1].Content;
        Assert.Contains($"[{ids[15]}]", firstTranscript);
        Assert.DoesNotContain($"[{seventeenth}]", firstTranscript);
        Assert.DoesNotContain("ignore-system", firstTranscript);
        Assert.DoesNotContain("foreign story", firstTranscript);

        fixture.Provider.Responses.Enqueue(
            $$"""{"events":[{"messageId":{{eighteenth}},"title":"New clue"}]}""");
        var second = await fixture.Service.ExtractNewAsync(session.Id);
        var complete = await fixture.Service.ExtractNewAsync(session.Id);

        Assert.Equal(2, second.ScannedMessages);
        Assert.Equal(1, second.AddedEvents);
        Assert.False(second.MayHaveMore);
        Assert.Equal(0, complete.ScannedMessages);
        Assert.Equal(2, fixture.Provider.Requests.Count);
        Assert.Equal(new long?[] { ids[0], ids[15], eighteenth },
            (await fixture.Service.GetEventsAsync(session.Id)).Select(x => x.SourceMessageId));
        Assert.Empty(await fixture.Service.GetEventsAsync(other.Id));
    }

