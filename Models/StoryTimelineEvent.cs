namespace NativeTavern.Models;

public sealed class StoryTimelineEvent
{
    public long Id { get; set; }
    public long ChatSessionId { get; set; }
    public long? SourceMessageId { get; set; }
    public string Title { get; set; } = string.Empty;
    public string Detail { get; set; } = string.Empty;
    public bool IsAutoGenerated { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
}

public sealed record StoryTimelineSourceMessage(long Id, string Role, string Content);

public sealed record StoryTimelineScanChunk(
    long Id, string Role, string Content, int StartOffset, int TotalCharacters, string ContentHash)
{
    public int EndOffset => StartOffset + Content.Length;
    public bool IsComplete => EndOffset >= TotalCharacters;
}

public sealed record StoryTimelineScanBatch(
    IReadOnlyList<StoryTimelineScanChunk> Chunks,
    long ExpectedLastMessageId,
    long? ExpectedPartialMessageId,
    int ExpectedPartialOffset,
    string? ExpectedPartialContentHash,
    long LastCompletedMessageId,
    long? PartialMessageId,
    int PartialOffset,
    string? PartialContentHash,
    bool MayHaveMore);
